test('wheel paging animates one page per gesture and supports reverse and reduced motion', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/beta')
  const story = page.locator('.beta-story')
  await page.getByRole('region', { name: 'About Oro', exact: true }).hover()
  await page.mouse.wheel(0, 120)
  await expect(story).toHaveAttribute('data-phase', 'leaving')
  await page.getByRole('region', { name: 'About Oro', exact: true }).evaluate(async (region) => {
    for (let event = 0; event < 32; event++) {
      region.dispatchEvent(new WheelEvent('wheel', { deltaY: 40, bubbles: true, cancelable: true }))
      await new Promise((resolve) => setTimeout(resolve, 40))
    }
  })
  await expect(page.locator('#our-vision')).toBeVisible()
  await expect(story).toHaveAttribute('data-phase', 'idle')
  await expect(page.locator('#our-vision .beta-chapter-content')).toHaveCSS('opacity', '1')
  await expect(page.locator('.beta-chapter')).toHaveCount(1)
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  await page.mouse.wheel(0, -120)
  await expect(page.getByRole('heading', { name: 'Help us make Oro yours.' })).toBeVisible()
  await expect(story).toHaveAttribute('data-phase', 'idle')
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(story).toHaveAttribute('data-phase', 'leaving')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(story).toHaveAttribute('data-phase', 'idle')
  await expect(page.locator('#our-vision')).toBeVisible()
  await expect(page.locator('.beta-chapter-content')).toHaveCSS('animation-name', 'none')
  await page.getByRole('region', { name: 'About Oro', exact: true }).focus()
  await page.keyboard.press('ArrowLeft')
  await expect(page.getByRole('heading', { name: 'Help us make Oro yours.' })).toBeVisible()
})

