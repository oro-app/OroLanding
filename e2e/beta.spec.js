test.describe('touch invitation navigation', () => {
  test.use({ hasTouch: true, viewport: { width: 390, height: 844 } })
  test('swipes forward and back without scrolling the document', async ({ page }) => {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/beta')
    await expect(page.getByRole('region', { name: 'About Oro', exact: true })).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    const client = await page.context().newCDPSession(page)
    async function swipe(from, to) {
      await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 195, y: from }] })
      await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 195, y: to }] })
      await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    }
    await swipe(640, 360)
    await expect(page.locator('#our-vision-title')).toBeVisible()
    await swipe(360, 640)
    await expect(page.getByRole('heading', { name: 'Help us make Oro yours.' })).toBeVisible()
    expect(await page.evaluate(() => window.scrollY)).toBe(0)
    await page.getByRole('link', { name: 'Skip to the form' }).click()
    await expect(page.getByRole('heading', { name: 'First, what’s your name?' })).toBeVisible()
  })
})

